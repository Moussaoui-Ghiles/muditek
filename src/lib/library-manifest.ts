function skillPresentation(
  slug: string,
  answer: string,
  inputs: string[],
  outputs: string[],
  prerequisites: string[],
  source: string,
  examplePath: string,
): LibraryPresentation {
  return {
    version: "1.0.0",
    answer,
    inputs,
    outputs,
    prerequisites,
    bundleFiles: SKILL_BUNDLE_FILES[slug] ?? [],
    examplePath,
    validationCommand: `node scripts/validate-library-skill.mjs ${source} ${examplePath}`,
    sourceLinks: [
      { label: "Public instructions", href: `/skills/${slug}#instructions` },
    ],
  };
}

function playbookPresentation(
  slug: string,
  answer: string,
  inputs: string[],
  outputs: string[],
  prerequisites: string[],
): LibraryPresentation {
  return {
    version: "1.0.0",
    answer,
    inputs,
    outputs,
    prerequisites,
    bundleFiles: [],
    examplePath: `/api/library/playbooks/${slug}`,
    validationCommand: null,
    sourceLinks: [
      { label: "Original playbook", href: `/api/library/playbooks/${slug}` },
    ],
  };
}

function toolPresentation(
  answer: string,
  inputs: string[],
  outputs: string[],
  prerequisites: string[],
  methodHref: string,
): LibraryPresentation {
  return {
    version: "1.0.0",
    answer,
    inputs,
    outputs,
    prerequisites,
    bundleFiles: [],
    examplePath: methodHref,
    validationCommand: null,
    sourceLinks: [{ label: "Method source", href: methodHref }],
  };
}

