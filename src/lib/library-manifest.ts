export const LIBRARY_MANIFEST: readonly LibraryItem[] = LIBRARY_MANIFEST_BASE.map((item) => ({
  ...item,
  ...presentationFor(item),
}));

const KIND_SEGMENTS: Record<string, LibraryKind> = {
  skills: "skill",
  playbooks: "playbook",
  tools: "tool",
};

export function getPublishedLibraryItems(kind?: LibraryKind): LibraryItem[] {
  return LIBRARY_MANIFEST.filter(
    (item) => item.status === "published" && (!kind || item.kind === kind),
  );
}

export function getLibraryItem(kind: LibraryKind, slug: string): LibraryItem | null {
  return LIBRARY_MANIFEST.find((item) => item.kind === kind && item.slug === slug) ?? null;
}

export type LibraryPathResolution =
  | { status: "published"; item: LibraryItem }
  | { status: "redirect"; target: string }
  | { status: "gone" }
  | { status: "not-found" };

export function resolveLibraryPath(pathname: string): LibraryPathResolution {
  const cleanPath = pathname.split(/[?#]/, 1)[0].replace(/\/+$/, "") || "/";
  const [, segment, slug, ...rest] = cleanPath.split("/");
  const kind = KIND_SEGMENTS[segment];
  if (!kind || !slug || rest.length > 0) return { status: "not-found" };

  const item = getLibraryItem(kind, decodeURIComponent(slug));
  if (!item) return { status: "not-found" };
  if (item.status === "published") return { status: "published", item };
  if (item.status === "redirected" && item.redirectTarget) {
    return { status: "redirect", target: item.redirectTarget };
  }
  return { status: "gone" };
}
